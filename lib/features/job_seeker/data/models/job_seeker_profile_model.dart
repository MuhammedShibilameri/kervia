import '../../domain/entities/job_seeker_profile_entity.dart';

class JobSeekerProfileModel extends JobSeekerProfileEntity {
  const JobSeekerProfileModel({
    required super.userId,
    super.fullName,
    super.email,
    super.phoneNumber,
    super.dateOfBirth,
    super.gender,
    super.currentLocation,
    super.state,
    super.district,
    super.taluk,
    super.panchayat,
    super.photoUrl,
    super.highestQualification,
    super.currentOccupation,
    super.yearsOfExperience,
    super.currentSalary,
    super.expectedSalary,
    super.skills,
    super.languages,
    super.preferredLocations,
    super.workMode,
    super.salaryType,
    super.preferredCategories,
    super.employmentTypes,
    super.resumeName,
    super.resumeSize,
    super.resumePath,
    super.videoName,
    super.videoSize,
    super.videoPath,
    super.declarationsConfirmed,
    super.termsAgreed,
    super.stepCompleted,
    super.isSubmitted,
    super.notificationsEnabled,
  });

  factory JobSeekerProfileModel.fromEntity(JobSeekerProfileEntity entity) {
    return JobSeekerProfileModel(
      userId: entity.userId,
      fullName: entity.fullName,
      email: entity.email,
      phoneNumber: entity.phoneNumber,
      dateOfBirth: entity.dateOfBirth,
      gender: entity.gender,
      currentLocation: entity.currentLocation,
      state: entity.state,
      district: entity.district,
      taluk: entity.taluk,
      panchayat: entity.panchayat,
      photoUrl: entity.photoUrl,
      highestQualification: entity.highestQualification,
      currentOccupation: entity.currentOccupation,
      yearsOfExperience: entity.yearsOfExperience,
      currentSalary: entity.currentSalary,
      expectedSalary: entity.expectedSalary,
      skills: entity.skills,
      languages: entity.languages,
      preferredLocations: entity.preferredLocations,
      workMode: entity.workMode,
      salaryType: entity.salaryType,
      preferredCategories: entity.preferredCategories,
      employmentTypes: entity.employmentTypes,
      resumeName: entity.resumeName,
      resumeSize: entity.resumeSize,
      resumePath: entity.resumePath,
      videoName: entity.videoName,
      videoSize: entity.videoSize,
      videoPath: entity.videoPath,
      declarationsConfirmed: entity.declarationsConfirmed,
      termsAgreed: entity.termsAgreed,
      stepCompleted: entity.stepCompleted,
      isSubmitted: entity.isSubmitted,
      notificationsEnabled: entity.notificationsEnabled,
    );
  }

  factory JobSeekerProfileModel.fromMap(Map<String, dynamic> map, String id) {
    return JobSeekerProfileModel(
      userId: id,
      fullName: map['fullName'] as String? ?? '',
      email: map['email'] as String? ?? '',
      phoneNumber: map['phoneNumber'] as String? ?? '',
      dateOfBirth: map['dateOfBirth'] as String? ?? '',
      gender: map['gender'] as String? ?? '',
      currentLocation: map['currentLocation'] as String? ?? '',
      state: map['state'] as String? ?? 'Kerala',
      district: map['district'] as String? ?? '',
      taluk: map['taluk'] as String? ?? '',
      panchayat: map['panchayat'] as String? ?? '',
      photoUrl: map['photoUrl'] as String?,
      highestQualification: map['highestQualification'] as String? ?? '',
      currentOccupation: map['currentOccupation'] as String? ?? '',
      yearsOfExperience: map['yearsOfExperience'] as String? ?? '',
      currentSalary: map['currentSalary'] as String? ?? '0.00',
      expectedSalary: map['expectedSalary'] as String? ?? '0.00',
      skills: List<String>.from(map['skills'] ?? const []),
      languages: List<String>.from(map['languages'] ?? const []),
      preferredLocations: List<String>.from(map['preferredLocations'] ?? const []),
      workMode: map['workMode'] as String? ?? 'Hybrid',
      salaryType: map['salaryType'] as String? ?? 'Annual',
      preferredCategories: map['preferredCategories'] as String? ?? '',
      employmentTypes: List<String>.from(map['employmentTypes'] ?? const []),
      resumeName: map['resumeName'] as String?,
      resumeSize: map['resumeSize'] as String?,
      resumePath: map['resumePath'] as String?,
      videoName: map['videoName'] as String?,
      videoSize: map['videoSize'] as String?,
      videoPath: map['videoPath'] as String?,
      declarationsConfirmed: (map['declarationsConfirmed'] as bool?) ?? false,
      termsAgreed: (map['termsAgreed'] as bool?) ?? false,
      stepCompleted: (map['stepCompleted'] as int?) ?? 1,
      isSubmitted: (map['isSubmitted'] as bool?) ?? false,
      notificationsEnabled: (map['notificationsEnabled'] as bool?) ?? true,
    );
  }

  Map<String, dynamic> toMap() {
    return {
      'fullName': fullName,
      'email': email,
      'phoneNumber': phoneNumber,
      'dateOfBirth': dateOfBirth,
      'gender': gender,
      'currentLocation': currentLocation,
      'state': state,
      'district': district,
      'taluk': taluk,
      'panchayat': panchayat,
      'photoUrl': photoUrl,
      'highestQualification': highestQualification,
      'currentOccupation': currentOccupation,
      'yearsOfExperience': yearsOfExperience,
      'currentSalary': currentSalary,
      'expectedSalary': expectedSalary,
      'skills': skills,
      'languages': languages,
      'preferredLocations': preferredLocations,
      'workMode': workMode,
      'salaryType': salaryType,
      'preferredCategories': preferredCategories,
      'employmentTypes': employmentTypes,
      'resumeName': resumeName,
      'resumeSize': resumeSize,
      'resumePath': resumePath,
      'videoName': videoName,
      'videoSize': videoSize,
      'videoPath': videoPath,
      'declarationsConfirmed': declarationsConfirmed,
      'termsAgreed': termsAgreed,
      'stepCompleted': stepCompleted,
      'isSubmitted': isSubmitted,
      'notificationsEnabled': notificationsEnabled,
      'updatedAt': DateTime.now().toIso8601String(),
    };
  }
}
